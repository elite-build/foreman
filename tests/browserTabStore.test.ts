import { beforeAll, expect, it, vi } from 'vitest'
let store: typeof import('../src/renderer/src/store')
const command = vi.fn(async () => null)
beforeAll(async () => {
  vi.stubGlobal('window', { foreman: { invoke: {}, browser: { command }, send: { setUnread() {} }, onEvent() {} }, addEventListener() {}, dispatchEvent() {} })
  vi.stubGlobal('localStorage', { getItem: () => null, setItem() {} })
  vi.stubGlobal('document', { hasFocus: () => true })
  store = await import('../src/renderer/src/store')
})
it('keeps one browser per workspace and switching chats never destroys the native page', () => {
  store.openBrowserTab('w1', 'http://localhost:50230/')
  store.openBrowserTab('w1', 'http://localhost:50230/next')
  expect(Object.keys(store.getState().browserTabs)).toEqual(['w1'])
  store.selectSession('w1', 's2')
  expect(store.getState().browserTabs.w1.active).toBe(false)
  expect(store.getState().browserTabs.w1.url).toBe('http://localhost:50230/next')
  expect(command).not.toHaveBeenCalled()
  store.selectBrowserTab('w1', true)
  store.splitBrowserTab('w1', true)
  expect(store.getState().browserTabs.w1).toMatchObject({ active: true, split: true })
  store.closeBrowserTab('w1')
  expect(store.getState().browserTabs.w1).toBeUndefined()
  expect(command).toHaveBeenCalledWith('w1', { type: 'close' })
})
it('delivers screenshot context and attachments once without replacing or sending a chat', () => {
  const attachment = { name: 'browser.png', path: '/workspace/browser.png', kind: 'image' } as never
  store.openBrowserTab('w1', 'http://localhost:50230/')
  store.fillComposer('w1', 's2', 'Browser screenshot', undefined, [attachment])
  expect(store.getState().activeSession.w1).toBe('s2')
  expect(store.getState().browserTabs.w1.active).toBe(false)
  expect(store.takeComposerFill('s1')).toBeNull()
  expect(store.takeComposerFill('s2')).toMatchObject({ text: 'Browser screenshot', attachments: [attachment] })
  expect(store.takeComposerFill('s2')).toBeNull()
})
