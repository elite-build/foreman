// The protocols the adapters are written against are pinned (docs/agents.md, 4.2): an installed package that moved, or a
// generated folder someone edited, fails here until the pins are regenerated and the fixtures re-recorded.
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { ACP_SCHEMAS, CODEX_PROTOCOL_DIR, currentPins, folderHash, pinProblems, readPins } from '../scripts/gen-agent-protocols.mjs'

const root = path.resolve(__dirname, '..')

describe('agent protocol pins', () => {
  it('match the installed packages and the generated Codex folder', () => {
    expect(pinProblems(root)).toEqual([])
  })

  it('pin every protocol the adapters speak', () => {
    const pins = readPins(root)
    expect(pins.codex.version).toMatch(/^\d+\.\d+\.\d+/)
    expect(pins.codex.generated.files).toBeGreaterThan(100)
    expect(Object.keys(pins.acp.schemas)).toEqual(ACP_SCHEMAS)
    expect(pins.acp.schemas['schema/v1/schema.json']).toMatch(/^[0-9a-f]{64}$/)
    expect(pins.acp.schemas['schema/v2/schema.json']).toMatch(/^[0-9a-f]{64}$/)
    expect(pins.claudeAgentSdk.types.sha256).toMatch(/^[0-9a-f]{64}$/)
  })

  it('names the version that differs, and says what to run', () => {
    const pins = readPins(root)
    const stale = structuredClone(pins)
    stale.codex.version = '0.0.1'
    stale.claudeAgentSdk.version = '0.0.1'
    stale.codex.generated.sha256 = '0'.repeat(64)
    stale.acp.schemas['schema/v2/schema.json'] = '0'.repeat(64)
    const problems = pinProblems(root, stale)
    expect(problems).toHaveLength(4)
    expect(problems.join('\n')).toContain(`@openai/codex version: pinned 0.0.1, now ${currentPins(root).codex.version}`)
    expect(problems.join('\n')).toContain('edited by hand')
    expect(problems.every((p) => p.includes('npm run gen:agent-protocols'))).toBe(true)
  })

  it('hashes the generated folder by content, not by line endings', () => {
    const a = folderHash(path.join(root, CODEX_PROTOCOL_DIR))
    expect(a.sha256).toBe(readPins(root).codex.generated.sha256)
    expect(a.files).toBe(readPins(root).codex.generated.files)
  })

  it('pins the Claude Agent SDK exactly in package.json', () => {
    const dependencies = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')).dependencies as Record<string, string>
    expect(dependencies['@anthropic-ai/claude-agent-sdk']).toBe(readPins(root).claudeAgentSdk.version)
    expect(dependencies['@anthropic-ai/claude-agent-sdk']).toMatch(/^\d+\.\d+\.\d+$/)
  })

  it('marks every generated file with the generated header', () => {
    const sample = readFileSync(path.join(root, CODEX_PROTOCOL_DIR, 'ClientRequest.ts'), 'utf8')
    expect(sample.startsWith('// Generated by scripts/gen-agent-protocols.mjs')).toBe(true)
  })
})
