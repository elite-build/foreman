// Writes the stylesheet for ui-review mocks: the app's real tokens from src/renderer/src/ui/tokens.css under
// [data-theme] selectors (a mock page toggles light and dark itself, where the app follows prefers-color-scheme),
// followed by ../assets/mock-controls.css, with the Geist fonts copied into fonts/ beside it. Usage: node .claude/skills/ui-review/scripts/mock-tokens.mjs <out.css>
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '../../../..')
const out = process.argv[2]
if (!out) {
  console.error('usage: node mock-tokens.mjs <out.css>')
  process.exit(1)
}

const tokens = readFileSync(path.join(root, 'src/renderer/src/ui/tokens.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')

/** The body of the first `{ … }` that opens at or after `from`, braces balanced. */
function block(text, from) {
  const open = text.indexOf('{', from)
  if (open === -1) return null
  let depth = 0
  for (let i = open; i < text.length; i++) {
    if (text[i] === '{') depth++
    else if (text[i] === '}' && --depth === 0) return { body: text.slice(open + 1, i), end: i + 1 }
  }
  return null
}

// tokens.css: `:root { … }` holds every token with the dark values, then `@media (prefers-color-scheme: light)
// { :root { … } }` overrides them for light. Colour-vision, forced-colour and motion rules don't apply to mocks.
const base = block(tokens, tokens.indexOf(':root'))
const lightMedia = tokens.indexOf('@media (prefers-color-scheme: light)')
const light = lightMedia === -1 ? null : block(tokens, tokens.indexOf(':root', lightMedia))
if (!base || !light) {
  console.error('tokens.css no longer has a :root block followed by a light-theme :root block; update mock-tokens.mjs')
  process.exit(1)
}

const tidy = (body) => body.split('\n').map((l) => l.trim()).filter(Boolean).map((l) => `  ${l}`).join('\n')
const controls = readFileSync(path.join(here, '../assets/mock-controls.css'), 'utf8')

// The app's fonts, copied beside the stylesheet so the mocks don't depend on a worktree's node_modules.
const fonts = [
  ['Geist Variable', '@fontsource-variable/geist/files/geist-latin-wght-normal.woff2'],
  ['Geist Mono Variable', '@fontsource-variable/geist-mono/files/geist-mono-latin-wght-normal.woff2']
]
const fontDir = path.join(path.dirname(path.resolve(out)), 'fonts')
mkdirSync(fontDir, { recursive: true })
const faces = fonts
  .filter(([, file]) => existsSync(path.join(root, 'node_modules', file)))
  .map(([family, file]) => {
    copyFileSync(path.join(root, 'node_modules', file), path.join(fontDir, path.basename(file)))
    return `@font-face { font-family: '${family}'; src: url('fonts/${path.basename(file)}') format('woff2'); font-weight: 100 900; font-display: block; }`
  })
  .join('\n')

writeFileSync(
  out,
  `/* Generated by .claude/skills/ui-review/scripts/mock-tokens.mjs from src/renderer/src/ui/tokens.css. Regenerate;
   don't edit. Light is the default; <html data-theme="dark"> switches. */
${faces}
:root, [data-theme='dark'] {
${tidy(base.body)}
}
:root:not([data-theme='dark']), [data-theme='light'] {
${tidy(light.body)}
}

${controls}`
)
console.log(`wrote ${out}`)
