// docs/cli.md, rendered from the command table and the help renderers so it can't drift from `foreman help`.
// Regenerate it with `npm run docs:cli`; tests/cliDocs.test.ts fails while the committed file is stale.
import { COMMANDS, GROUP_LABELS, GROUP_ORDER, commandName, visibleCommands, type CommandSpec } from '../shared/cliCommands'
import { renderCommandHelp, renderHelp, renderTopic } from './help'
import './topics/settingsKeys'
import { CLI_VERSION } from './version'

const fence = (text: string): string => ['```text', text, '```'].join('\n')

function topic(name: string): string {
  const text = renderTopic(name)
  if (text === undefined) throw new Error(`no help topic “${name}”`)
  return fence(text)
}

/** The whole of docs/cli.md. Pure and deterministic: no dates, paths or version number. */
export function renderDocs(commands: CommandSpec[] = COMMANDS): string {
  // The release number would make the file change on every release; the header line says the rest.
  const overview = renderHelp(commands).replace(`foreman ${CLI_VERSION} · `, 'foreman · ')
  const out: string[] = [
    '# The foreman command',
    '',
    '<!-- Generated by `npm run docs:cli` from the command table. Do not edit by hand. -->',
    '',
    'The `foreman` command drives the running Foreman app from a terminal: start workspaces from templates, send and wait for turns, change settings, manage repositories, pull requests, schedules and remote workspaces. It talks to the app over a local socket in the data folder (a named pipe on Windows) that only you can read, so Foreman must be running. Install it from **Settings → Advanced → foreman command → Install**, or from a checkout with `npm run build && npm link`.',
    '',
    '`foreman help` lists everything:',
    '',
    fence(overview),
    '',
    '## Exit codes',
    '',
    topic('exit-codes'),
    '',
    '## Inside an agent turn',
    '',
    topic('agents'),
    '',
    '## Environment variables',
    '',
    topic('environment'),
    ''
  ]
  for (const group of GROUP_ORDER) {
    const specs = visibleCommands(commands).filter((c) => c.group === group)
    if (!specs.length) continue
    out.push(`## ${GROUP_LABELS[group]}`, '')
    for (const spec of specs) out.push(`### foreman ${commandName(spec)}`, '', fence(renderCommandHelp(spec)), '')
  }
  out.push('## Settings keys', '', topic('settings-keys'), '')
  return out.join('\n')
}
